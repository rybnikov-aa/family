/**
 * Реестр прикладных (SPA) проектов — карточки в разделе «Проекты» для проектов,
 * переехавших из статических страниц в код приложения (strangler fig).
 *
 * В отличие от статичных проектов (подпапки `PROJECTS_DIR` с `index.html`),
 * прикладной проект определяется записью в этом реестре и не зависит от наличия
 * статичной папки. `listProjects` объединяет оба источника и отдаёт их единым
 * списком (при совпадении `slug` реестр перекрывает статику).
 */

export interface AppProject {
  /** Ключ проекта (`slug`) — уникален среди статичных и прикладных проектов. */
  slug: string;
  /** Название карточки в разделе «Проекты». */
  title: string;
  /** Описание карточки. */
  description: string;
  /** Акцентный цвет карточки (hex). */
  accent: string;
  /** Имя иконки из `projectIcons` на фронтенде (например `renovation`). */
  icon: string;
  /** Порядок в списке (меньше — раньше), как `project-order` у статичных. */
  order: number;
  /** Внутренний маршрут приложения без `#` (hash-роутинг), например `/projects/renovation`. */
  route: string;
}

