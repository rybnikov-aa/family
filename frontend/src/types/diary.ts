/**
 * Изображение события «Дневника» в форме: новое (с файлом) или уже сохранённое.
 * Общий тип для формы события, модалки фотографий и связанных компонентов.
 */
export interface FormImage {
  /** Клиентский id нового файла (`new-N`) либо имя существующего файла. */
  id: string;
  /** Новый файл для загрузки; `null` — уже сохранённое изображение. */
  file: File | null;
  /** Превью: object URL (новое) либо серверный URL (существующее). */
  preview: string;
}
